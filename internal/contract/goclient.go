// goErrorCodes is every registered code as a constant of the root package,
// for comparing with Error.Code.
func goErrorCodes() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by `go generate ./internal/contract` from ContentKit's error-code registry. DO NOT EDIT.\n\npackage contentkit\n\n")
	b.WriteString("// Error.Code is one of these; docs/api/routes.md lists each route's.\nconst (\n")
	for _, c := range httpapi.ErrorCodes() {
		fmt.Fprintf(&b, "\t// Code%s (%d): %s\n\tCode%s = %q\n", pascal(c.Code), c.Status, c.Meaning, pascal(c.Code), c.Code)
	}
	b.WriteString(")\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

// goMethod names a route's client method: its HTTP verb, then its path's
// literal segments in Pascal case, each singular before a wildcard naming
// one item:
// PATCH /v1/entities/{id} is PatchEntity, PUT /v1/contents/{id}/versions/{vid}/offer
// PutContentVersionOffer.
func goMethod(r httpapi.Spec) string {
	name := pascal(strings.ToLower(r.Method))
	segs := strings.Split(strings.TrimPrefix(r.FullPath(), httpapi.Version+"/"), "/")
	for i, seg := range segs {
		if strings.HasPrefix(seg, "{") {
			// A terminal kind selects a collection, not one item's ID.
			// Keep it in the method name: /manage and /manage/{kind}
			// are GetManage and GetManageKind respectively.
			if seg == "{kind}" && i == len(segs)-1 {
				name += "Kind"
			}
			continue
		}
		if i+1 < len(segs) && strings.HasPrefix(segs[i+1], "{") && !strings.HasSuffix(segs[i+1], "...}") {
			seg = singular(seg)
		}
		name += pascal(seg)
	}
	return name
}

func singular(s string) string {
	switch {
	case strings.HasSuffix(s, "ies"):
		return strings.TrimSuffix(s, "ies") + "y"
	case strings.HasSuffix(s, "s") && !strings.HasSuffix(s, "ss"):
		return strings.TrimSuffix(s, "s")
	}
	return s
}

// pascal joins s's words (split at '-', '_' and '.') capitalized.
func pascal(s string) string {
	var b strings.Builder
	for _, w := range strings.FieldsFunc(s, func(r rune) bool { return r == '-' || r == '_' || r == '.' }) {
		r := []rune(w)
		b.WriteRune(unicode.ToUpper(r[0]))
		b.WriteString(string(r[1:]))
	}
	return b.String()
}

// goImports names the packages a generated file uses.
type goImports struct {
	byPath map[string]string
	names  map[string]bool
	std    map[string]bool // fmt and strings, when used
}

func (g *goImports) qualify(pkgPath string) string {
	if pkgPath == module {
		return ""
	}
	if name, ok := g.byPath[pkgPath]; ok {
		return name + "."
	}
	name := path.Base(pkgPath)
	for n := 2; g.names[name]; n++ {
		name = fmt.Sprintf("%s%d", path.Base(pkgPath), n)
	}
	g.byPath[pkgPath], g.names[name] = name, true
	return name + "."
}

// goType is t as Go source.
func (g *goImports) goType(t reflect.Type) (string, error) {
	switch t.Kind() {
	case reflect.Pointer:
		e, err := g.goType(t.Elem())
		return "*" + e, err
	case reflect.Slice:
		e, err := g.goType(t.Elem())
		return "[]" + e, err
	case reflect.Map:
		k, err := g.goType(t.Key())
		if err != nil {
			return "", err
		}
		v, err := g.goType(t.Elem())
		return "map[" + k + "]" + v, err
	case reflect.Interface:
		if t.Name() == "" {
			return "any", nil
		}
	}
	if t.Name() == "" || strings.Contains(t.Name(), "[") {
		return "", fmt.Errorf("contract: the Go client cannot name %s", t)
	}
	if t.PkgPath() == "" {
		return t.Name(), nil
	}
	return g.qualify(t.PkgPath()) + t.Name(), nil
}

// goParam is a path wildcard as a Go parameter name.
func goParam(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' })
	id := parts[0] + pascal(strings.Join(parts[1:], "_"))
	if token.IsKeyword(id) || slices.Contains([]string{"ctx", "body", "q", "c"}, id) {
		id += "Arg"
	}
	return id
}

var queryGoTypes = map[string]string{"string": "string", "integer": "int", "number": "float64", "boolean": "*bool", "flag": "bool",
	"strings": "[]string", "list": "[]string"}

// goClient is the Go client: per route a method on Client sending it through
// the client's transport, and the route's query as a struct.
func (m *model) goClient() ([]byte, error) {
	imp := &goImports{byPath: map[string]string{}, std: map[string]bool{},
		names: map[string]bool{"context": true, "fmt": true, "http": true, "strings": true, "url": true}}
	var body bytes.Buffer
	seen := map[string]string{}
	for _, r := range m.routes {
		name := goMethod(r)
		if other, dup := seen[name]; dup {
			return nil, fmt.Errorf("contract: %s and %s %s are both Client.%s", other, r.Module, r.Key(), name)
		}
		seen[name] = string(r.Module) + " " + r.Key()
		if err := m.goRoute(&body, imp, name, r); err != nil {
			return nil, fmt.Errorf("contract: %s %s: %w", r.Module, r.Key(), err)
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by `go generate ./internal/contract` from ContentKit's route catalog. DO NOT EDIT.\n\npackage contentkit\n\nimport (\n\t\"context\"\n")
	for _, p := range []string{"fmt", "net/http", "net/url", "strings"} {
		if p == "net/http" || p == "net/url" || imp.std[p] {
			fmt.Fprintf(&b, "\t%q\n", p)
		}
	}
	b.WriteString("\n")
	paths := make([]string, 0, len(imp.byPath))
	for p := range imp.byPath {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		if imp.byPath[p] == path.Base(p) {
			fmt.Fprintf(&b, "\t%q\n", p)
		} else {
			fmt.Fprintf(&b, "\t%s %q\n", imp.byPath[p], p)
		}
	}
	b.WriteString(")\n")
	b.Write(body.Bytes())
	return format.Source(b.Bytes())
}

func (m *model) goRoute(b *bytes.Buffer, imp *goImports, name string, r httpapi.Spec) error {
	args := []string{"ctx context.Context"}
	pathExpr := `"` + r.FullPath() + `"`
	var escapes []string
	for _, p := range pathParams(r.Path) {
		id := goParam(p)
		args = append(args, id+" string")
		wildcard := "{" + p + "}"
		esc := "url.PathEscape(" + id + ")"
		if strings.Contains(r.Path, "{"+p+"...}") {
			wildcard, esc = "{"+p+"...}", "escapePath("+id+")"
		}
		escapes = append(escapes, fmt.Sprintf("%q, %s", wildcard, esc))
	}
	if len(escapes) > 0 {
		pathExpr = fmt.Sprintf("expand(%s, %s)", pathExpr, strings.Join(escapes, ", "))
	}
	in := "nil"
	if r.Request != nil {
		t, err := imp.goType(reflect.TypeOf(r.Request))
		if err != nil {
			return err
		}
		args, in = append(args, "body "+t), "body"
	}
	query := "nil"
	if len(r.Query) > 0 {
		qt := name + "Query"
		fmt.Fprintf(b, "\n// %s is the query of %s.\ntype %s struct {\n", qt, name, qt)
		for _, p := range r.Query {
			fmt.Fprintf(b, "\t// %s\n\t%s %s\n", p.Doc, queryGoName(p.Name), queryGoTypes[p.Kind])
		}
		b.WriteString("}\n")
		fmt.Fprintf(b, "\nfunc (q %s) values() url.Values {\n\tv := url.Values{}\n", qt)
		for _, p := range r.Query {
			f := "q." + queryGoName(p.Name)
			switch p.Kind {
			case "string":
				fmt.Fprintf(b, "\tif %s != \"\" {\n\t\tv.Set(%q, %s)\n\t}\n", f, p.Name, f)
			case "integer", "number":
				fmt.Fprintf(b, "\tif %s != 0 {\n\t\tv.Set(%q, fmt.Sprint(%s))\n\t}\n", f, p.Name, f)
			case "boolean":
				fmt.Fprintf(b, "\tif %s != nil {\n\t\tv.Set(%q, fmt.Sprint(*%s))\n\t}\n", f, p.Name, f)
			case "flag":
				fmt.Fprintf(b, "\tif %s {\n\t\tv.Set(%q, \"\")\n\t}\n", f, p.Name)
			case "strings":
				fmt.Fprintf(b, "\tfor _, s := range %s {\n\t\tv.Add(%q, s)\n\t}\n", f, p.Name)
			case "list":
				fmt.Fprintf(b, "\tif len(%s) > 0 {\n\t\tv.Set(%q, strings.Join(%s, \",\"))\n\t}\n", f, p.Name, f)
			default:
				return fmt.Errorf("query %s has kind %q", p.Name, p.Kind)
			}
		}
		b.WriteString("\treturn v\n}\n")
		args, query = append(args, "q "+qt), "q.values()"
	}
	var types []string
	stream := false
	for _, reply := range r.Responses {
		switch body := reply.Body.(type) {
		case nil:
		case httpapi.Stream:
			stream = true
		default:
			t, err := imp.goType(reflect.TypeOf(body))
			if err != nil {
				return err
			}
			if !slices.Contains(types, t) {
				types = append(types, t)
			}
		}
	}
	fmt.Fprintf(b, "\n// %s is %s %s (%s). %s\n", name, r.Method, r.FullPath(), r.Auth, r.Doc)
	sig := strings.Join(args, ", ")
	method := "http.Method" + pascal(strings.ToLower(r.Method))
	switch {
	case stream || len(types) > 1:
		fmt.Fprintf(b, "func (c *Client) %s(%s) (*Reply, error) {\n\treturn c.raw(ctx, %s, %s, %s, %s)\n}\n", name, sig, method, pathExpr, query, in)
	case len(types) == 1:
		fmt.Fprintf(b, "func (c *Client) %s(%s) (%s, error) {\n\tvar out %s\n\terr := c.call(ctx, %s, %s, %s, %s, &out)\n\treturn out, err\n}\n",
			name, sig, types[0], types[0], method, pathExpr, query, in)
	default:
		fmt.Fprintf(b, "func (c *Client) %s(%s) error {\n\treturn c.call(ctx, %s, %s, %s, %s, nil)\n}\n", name, sig, method, pathExpr, query, in)
	}
	for _, p := range r.Query {
		switch p.Kind {
		case "integer", "number", "boolean":
			imp.std["fmt"] = true
		case "list":
			imp.std["strings"] = true
		}
	}
	return nil
}

// queryGoName keeps domain Go fields canonical without changing HTTP parameters.
func queryGoName(name string) string {
	switch name {
	case "groups":
		return "Entities"
	case "exclude_groups":
		return "ExcludeEntities"
	case "owner_group":
		return "OwnerEntity"
	default:
		return pascal(name)
	}
}
